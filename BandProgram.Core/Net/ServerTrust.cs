	public static class ServerTrust
	{
		// HttpWebRequest.ServerCertificateValidationCallback에 넣는다.
		public static bool Validate(object sender, X509Certificate certificate, X509Chain chain, SslPolicyErrors errors)
		{
			try
			{
				X509Certificate2Collection extra = new X509Certificate2Collection();
				if (chain != null)
				{
					extra.AddRange(chain.ChainPolicy.ExtraStore);
					foreach (X509ChainElement element in chain.ChainElements)
					{
						extra.Add(element.Certificate);
					}
				}
				X509Certificate2 leaf = certificate == null ? null : certificate as X509Certificate2 ?? new X509Certificate2(certificate);
				return IsTrusted(leaf, extra, errors, DateTime.Now);
			}
			catch (Exception)
			{
				return false;
			}
		}

		internal static bool IsTrusted(X509Certificate2 leaf, X509Certificate2Collection extra, SslPolicyErrors errors, DateTime verificationTime)
		{
			if (errors == SslPolicyErrors.None)
			{
				return true;
			}
			if (leaf == null || errors != SslPolicyErrors.RemoteCertificateChainErrors)
			{
				return false;
			}
			using (X509Chain custom = new X509Chain())
			{
				custom.ChainPolicy.TrustMode = X509ChainTrustMode.CustomRootTrust;
				custom.ChainPolicy.CustomTrustStore.AddRange(Roots());
				custom.ChainPolicy.ExtraStore.AddRange(extra);
				custom.ChainPolicy.RevocationMode = X509RevocationMode.NoCheck;
				custom.ChainPolicy.DisableCertificateDownloads = true;
				custom.ChainPolicy.VerificationTime = verificationTime;
				return custom.Build(leaf);
			}
		}

		internal static X509Certificate2Collection Roots()
		{
			X509Certificate2Collection roots = new X509Certificate2Collection();
			roots.ImportFromPem(IsrgRootX1);
			roots.ImportFromPem(IsrgRootX2);
			return roots;
		}

